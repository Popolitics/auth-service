def read_key(name):
    # NAME_FILE points to a PEM file (relative to BASE_DIR); otherwise NAME holds the key with literal \n.
    path = os.getenv(f"{name}_FILE")
    if path:
        return (BASE_DIR / path).read_text()
    return os.getenv(name, "").replace("\\n", "\n")


